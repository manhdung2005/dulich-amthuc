const params = new URLSearchParams(window.location.search);
const dishKey = params.get("mon");
const dish = Object.prototype.hasOwnProperty.call(dishes, dishKey) ? dishes[dishKey] : null;
const detail = document.querySelector("[data-food-detail]");

if (!dish) {
    document.title = "Không tìm thấy món ăn | Du Lịch Miền Bắc";
    detail.innerHTML = `
        <section class="food-detail-error">
            <p class="food-kicker">ẨM THỰC MIỀN BẮC</p>
            <h1>Không tìm thấy món ăn</h1>
            <p>Đường dẫn món ăn không hợp lệ hoặc món này chưa có trang giới thiệu.</p>
            <a class="food-detail-back" href="amthuc.html">Quay lại danh sách món ngon</a>
        </section>`;
} else {
    const regionUrl = `amthuc.html#${dish.regionId}`;
    const setText = (selector, value) => {
        detail.querySelector(selector).textContent = value;
    };

    const titleName = dish.name.includes(dish.region) ? dish.name : `${dish.name} ${dish.region}`;
    document.title = `${titleName} | Du Lịch Miền Bắc`;
    document.querySelector('meta[name="description"]').setAttribute("content", dish.lead);
    setText("#food-region-link", dish.region);
    detail.querySelector("#food-region-link").href = regionUrl;
    setText("#food-breadcrumb-name", dish.name);
    setText("#food-image-tag", dish.region);
    setText("#food-kicker", `${dish.label} · ${dish.region.toLocaleUpperCase("vi-VN")}`);
    setText("#food-detail-title", dish.name);
    setText("#food-lead", dish.lead);
    setText("#food-story-title", dish.storyTitle);
    setText("#food-note-title", dish.noteTitle);
    setText("#food-note-copy", dish.note);
    setText("#food-footer-copy", `Còn nhiều món ngon đang chờ bạn ở ${dish.region}.`);
    detail.querySelector("#food-image").src = dish.image;
    detail.querySelector("#food-image").alt = dish.alt;
    detail.querySelector("#food-back-link").href = regionUrl;
    detail.querySelector("#food-footer-link").href = regionUrl;
    detail.querySelector("#food-back-link").lastChild.nodeValue = ` Xem thêm món ở ${dish.region}`;
    detail.querySelector("#food-footer-link").firstChild.nodeValue = `Khám phá thêm món ngon ${dish.region} `;
    detail.querySelector("#food-video-title").textContent = `Video giới thiệu ${dish.name}`;
    detail.querySelector(".food-video-input").setAttribute("aria-label", `Chọn video giới thiệu ${dish.name}`);
    detail.querySelector(".food-local-video").setAttribute("aria-label", `Video giới thiệu ${dish.name}`);

    const videoInput = detail.querySelector(".food-video-input");
    const previewVideo = detail.querySelector(".food-local-video");
    const videoMessage = detail.querySelector(".food-video-message");
    let previewUrl = "";

    videoInput.addEventListener("change", () => {
        const file = videoInput.files[0];
        if (!file) return;

        if (!file.type.startsWith("video/")) {
            if (previewUrl) URL.revokeObjectURL(previewUrl);
            previewUrl = "";
            previewVideo.removeAttribute("src");
            previewVideo.hidden = true;
            previewVideo.load();
            videoMessage.textContent = "Tệp đã chọn không phải video. Hãy chọn một tệp video khác.";
            videoInput.value = "";
            return;
        }

        if (previewUrl) URL.revokeObjectURL(previewUrl);
        previewUrl = URL.createObjectURL(file);
        previewVideo.src = previewUrl;
        previewVideo.hidden = false;
        previewVideo.load();
        videoMessage.textContent = `Đang xem thử: ${file.name}. Video chỉ nằm trên thiết bị này, chưa được tải lên máy chủ.`;
    });

    previewVideo.addEventListener("error", () => {
        videoMessage.textContent = "Không phát được tệp này. Hãy thử chọn video MP4 hoặc WebM.";
    });

    window.addEventListener("beforeunload", () => {
        if (previewUrl) URL.revokeObjectURL(previewUrl);
    });

    const storyBody = detail.querySelector("#food-story-body");
    dish.story.forEach((text) => {
        const paragraph = document.createElement("p");
        paragraph.textContent = text;
        storyBody.append(paragraph);
    });

    const tips = detail.querySelector("#food-tips");
    dish.tips.forEach(([title, text], index) => {
        const article = document.createElement("article");
        const number = document.createElement("span");
        const heading = document.createElement("h3");
        const paragraph = document.createElement("p");
        number.textContent = String(index + 1).padStart(2, "0");
        heading.textContent = title;
        paragraph.textContent = text;
        article.append(number, heading, paragraph);
        tips.append(article);
    });
}
